-- =============================================================================
-- 024: 郵便番号（brand_settings）
--   設計書 4.1 に対応
--
-- 領収書・請求書に載せる住所は、郵便番号から始まるのが日本の慣行。
-- 住所を1行に押し込むと、帳票で改行位置を選べない。
--
-- ハイフンは入れても入れなくてもよい。表示のときに整える。
-- =============================================================================

alter table public.brand_settings
  add column if not exists postal_code text;

comment on column public.brand_settings.postal_code is
  '郵便番号。7桁。ハイフンの有無は問わない。帳票の住所に使う。';
